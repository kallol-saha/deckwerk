/**
 * Generates src/shared/diagram/stencils/data.ts: draw.io's XML stencil sets
 * that DeckWerk ships, copied verbatim from the draw.io build.
 *
 *   node scripts/drawio-stencils.mjs [--drawio <webapp>]
 *
 * draw.io keeps every stencil set in js/stencils.min.js as
 * `f['<file>.xml'] = '<base64>'`: raw deflate of a compact binary form of the
 * XML (an op stream, three zig-zag varint streams for x, y and other numbers
 * — each delta coded — and a NUL-separated string table), decoded by the
 * function at the end of that file (and by src/shared/diagram/stencil.ts).
 * The strings are copied unchanged, so the data is exactly what draw.io
 * loads, at about a tenth of the size of the XML.
 *
 * The sets are those of the main palettes (Basic, Flowchart, Arrows) and
 * the libraries whose shapes are ported (electrical, networks), plus BPMN
 * and lean mapping. Add a file name to SETS and rerun to ship another.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const args = process.argv.slice(2).filter((a) => a !== '--');
let webapp = process.env.DRAWIO_WEBAPP ?? 'C:/Users/kallo/tools/drawio/src/main/webapp';
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--drawio') webapp = args[++i];
}

const SETS = [
  'basic.xml', 'flowchart.xml', 'arrows.xml', 'bpmn.xml', 'lean_mapping.xml', 'networks.xml',
  'electrical/abstract.xml', 'electrical/capacitors.xml', 'electrical/diodes.xml',
  'electrical/electro-mechanical.xml', 'electrical/iec417.xml', 'electrical/iec_logic_gates.xml',
  'electrical/inductors.xml', 'electrical/instruments.xml', 'electrical/logic_gates.xml',
  'electrical/miscellaneous.xml', 'electrical/mosfets1.xml', 'electrical/mosfets2.xml',
  'electrical/op_amps.xml', 'electrical/opto_electronics.xml', 'electrical/plc_ladder.xml',
  'electrical/power_semiconductors.xml', 'electrical/radio.xml', 'electrical/resistors.xml',
  'electrical/rot_mech.xml', 'electrical/signal_sources.xml', 'electrical/thermionic_devices.xml',
  'electrical/transistors.xml', 'electrical/transmission.xml', 'electrical/waveforms.xml',
];

const source = readFileSync(resolve(webapp, 'js/stencils.min.js'), 'utf8');
const entries = new Map();
for (const m of source.matchAll(/^f\['([^']+)'\] = '([A-Za-z0-9+/=]*)';$/gm)) entries.set(m[1], m[2]);

const version = readFileSync(resolve(webapp, '../../../VERSION'), 'utf8').trim();
const lines = [
  '/*',
  ` * draw.io's XML stencil sets (jgraph/drawio ${version}, src/main/webapp/js/stencils.min.js),`,
  ' * Copyright (c) 2006-2024, JGraph Ltd and draw.io AG, Apache License 2.0.',
  ' * Generated by scripts/drawio-stencils.mjs; do not edit. Each value is draw.io\'s',
  ' * encoding of one stencil file, unchanged (decoded by ../stencil.ts).',
  ' *',
  ' * draw.io\'s notice for its icon sets and stencil libraries: they may not be',
  ' * used as software assets in, distributed for use with, or incorporated into',
  ' * Atlassian products or products distributed through the Atlassian',
  ' * marketplace or plugin ecosystem without written permission; this does not',
  ' * apply to end-user diagram output.',
  ' */',
  '',
  '/** Encoded stencil sets by file name (as in mxStencilRegistry.libraries). */',
  'export const STENCIL_FILES: Readonly<Record<string, string>> = {',
];
let total = 0;
for (const name of SETS) {
  const data = entries.get(name);
  if (data == null) throw new Error(`not in stencils.min.js: ${name}`);
  total += data.length;
  lines.push(`  '${name}': '${data}',`);
}
lines.push('};', '');
const out = resolve(ROOT, 'src/shared/diagram/stencils/data.ts');
writeFileSync(out, lines.join('\n'), 'utf8');
console.log(`${SETS.length} stencil sets, ${total} characters, written to ${out}`);
